// Generates src/theme/tokens.generated.ts from tokens/tokens.json (the design system's source of truth).
// Run: pnpm tokens
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('../tokens/tokens.json', import.meta.url), 'utf8'));
const ref = (v) => (typeof v === 'string' && v.startsWith('{') ? `{colors.${v.slice(1, -1)}}` : v);
const raw = {},
  roles = {};
for (const c of t.color.tokens) {
  const v = c.value;
  const fixed = typeof v === 'string' || (v.light === v.dark && !String(v.light).startsWith('{'));
  if (c.name.startsWith('px-') || c.name.startsWith('class-') || c.name.startsWith('on-class'))
    raw[c.name] = { value: typeof v === 'string' ? v : v.light, description: c.usage };
  else
    roles[c.name] = {
      value:
        fixed && typeof v !== 'string'
          ? { _light: v.light, _dark: v.dark }
          : typeof v === 'string'
            ? v
            : { _light: ref(v.light), _dark: ref(v.dark) },
      description: c.usage,
    };
}
const fam = (name) => t.type.families[name];
const styles = {};
for (const g of t.type.groups)
  for (const s of g.styles)
    styles[s.name] = {
      description: s.usage,
      value: {
        fontFamily: s.family || g.family,
        fontSize: s.fontSize,
        lineHeight: s.lineHeight,
        fontWeight: String(s.fontWeight),
        ...(s.letterSpacing ? { letterSpacing: s.letterSpacing } : {}),
      },
    };
const list = (k) => Object.fromEntries((t[k]?.tokens || []).map((x) => [x.name, x]));
const sh = list('shadow');
const out = `// GENERATED by scripts/gen-tokens.mjs from tokens/tokens.json. Do not edit by hand.
export const rawColors = ${JSON.stringify(raw, null, 2)} as const;

/** Role, template and control colors with light and dark values. Aliases point at other color tokens. */
export const roleColors = ${JSON.stringify(roles, null, 2)} as const;

export const fontFamilies = ${JSON.stringify({ body: fam('sans'), heading: fam('sans'), mono: fam('mono'), display: fam('display') }, null, 2)} as const;

export const textStyleValues = ${JSON.stringify(styles, null, 2)} as const;

export const shadowValues = ${JSON.stringify(Object.fromEntries(Object.entries(sh).map(([k, v]) => [k.replace('shadow-', ''), { _light: v.value.light, _dark: v.value.dark }])), null, 2)} as const;

export const radiusValues = ${JSON.stringify(Object.fromEntries(Object.entries(list('radius')).map(([k, v]) => [k.replace('radius-', ''), v.value])), null, 2)} as const;

export const borderValues = ${JSON.stringify(Object.fromEntries(Object.entries(list('border')).map(([k, v]) => [k.replace('border-', ''), v.value])), null, 2)} as const;

export const pixelValues = ${JSON.stringify(Object.fromEntries(Object.entries(list('pixel')).map(([k, v]) => [k, v.value])), null, 2)} as const;
`;
writeFileSync(new URL('../src/theme/tokens.generated.ts', import.meta.url), out);
console.log('roles', Object.keys(roles).length, 'raw', Object.keys(raw).length, 'textStyles', Object.keys(styles).length);
